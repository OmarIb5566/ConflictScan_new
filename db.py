def _make_engine():
    if os.environ.get("CONFLICTSCAN_OFFLINE"):
        # `manage.py sql`: only the dialect is needed, never a connection (or the driver).
        from sqlalchemy import create_mock_engine
        return create_mock_engine(DATABASE_URL, lambda *a, **k: None)
    kwargs: dict = {"future": True, "pool_pre_ping": True}
    if IS_SQLITE:
        kwargs["connect_args"] = {"timeout": 30, "check_same_thread": False}
    eng = create_engine(DATABASE_URL, **kwargs)
    if IS_SQLITE:
        @event.listens_for(eng, "connect")
        def _sqlite_pragmas(dbapi_conn, _record):
            cur = dbapi_conn.cursor()
            cur.execute("PRAGMA foreign_keys = ON")
            cur.execute("PRAGMA journal_mode = WAL")
            cur.execute("PRAGMA busy_timeout = 30000")
            cur.close()
    return eng


engine = _make_engine()


def describe() -> str:
    """Engine + location without credentials, for logs and the health page."""
    from sqlalchemy.engine import make_url
    url = make_url(DATABASE_URL)
    where = url.database if IS_SQLITE else f"{url.host or ''}:{url.port or ''}/{url.database or ''}"
    return f"{url.get_backend_name()} {where}" + (f" (schema {SCHEMA})" if SCHEMA else "")
