def database_url() -> str:
    url = os.environ.get("DATABASE_URL")
    if url:
        return url
    os.makedirs(DATA_DIR, exist_ok=True)
    return "sqlite:///" + os.path.join(DATA_DIR, "conflictscan.db").replace("\\", "/")


DATABASE_URL = database_url()
IS_SQLITE = DATABASE_URL.startswith("sqlite")
SCHEMA: Optional[str] = None if IS_SQLITE else (os.environ.get("CONFLICTSCAN_DB_SCHEMA", "conflictscan") or None)


def qualified(name: str) -> str:
    return f"{SCHEMA}.{name}" if SCHEMA else name


def fk(target: str, **kw) -> ForeignKey:
    return ForeignKey(qualified(target), **kw)


