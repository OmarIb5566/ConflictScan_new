"""
Database definition - engine-neutral
====================================
One DATABASE_URL decides the engine; nothing else in the code is engine
specific. Tested on SQLite and PostgreSQL; written to run unchanged on SQL
Server (mssql+pyodbc) and, with their drivers, MySQL/MariaDB and Oracle.

Design rules that keep it portable (so the host company's DBA can take it
over without rewrites):

- Text primary keys (32-char hex), generated by the app - no sequences,
  identity columns or engine-specific auto-increment.
- Dates are stored as UTC timestamps without time zone; the app converts.
- JSON is stored as plain Unicode text (no JSONB / JSON column types), so
  every engine stores and backs it up the same way.
- All text is Unicode (NVARCHAR on SQL Server).
- Case-insensitive usernames use a lower-cased key column, not collations.
- No stored procedures, triggers, views or engine-specific SQL.
- Every object lives in one schema, "conflictscan" by default
  (CONFLICTSCAN_DB_SCHEMA), except on SQLite which has no schemas.
- The schema is created and upgraded only by Alembic migrations
  (migrations/); `python manage.py sql` prints them as plain SQL for a DBA
  who prefers to run them by hand.

Windows compatible.
"""

import json
